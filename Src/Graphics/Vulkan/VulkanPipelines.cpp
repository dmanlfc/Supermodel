bool PipelineCache::CreateSetLayout(const DeviceContext &device, SetLayoutId id,
                                    const VkDescriptorSetLayoutBinding *bindings, uint32_t count,
                                    std::string *error)
{
  VkDescriptorSetLayoutCreateInfo createInfo{};
  createInfo.sType = VK_STRUCTURE_TYPE_DESCRIPTOR_SET_LAYOUT_CREATE_INFO;
  createInfo.bindingCount = count;
  createInfo.pBindings = bindings;

  VkDescriptorSetLayout handle = VK_NULL_HANDLE;
  const VkResult result = vkCreateDescriptorSetLayout(device.device, &createInfo, nullptr, &handle);
  if (result != VK_SUCCESS)
    return SetError(error, VkError("vkCreateDescriptorSetLayout", result));

  m_setLayouts[static_cast<size_t>(id)] = handle;
  return true;
}

bool PipelineCache::CreateSetLayouts(const DeviceContext &device, std::string *error)
{
  // Every binding array comes straight from VulkanShaderInterface.h.
  if (!CreateSetLayout(device, SetLayoutId::R3D, kR3DDescriptorBindings.data(),
                       static_cast<uint32_t>(kR3DDescriptorBindings.size()), error))
    return false;
  if (!CreateSetLayout(device, SetLayoutId::ScrollFog, kScrollFogDescriptorBindings.data(),
                       static_cast<uint32_t>(kScrollFogDescriptorBindings.size()), error))
    return false;
  if (!CreateSetLayout(device, SetLayoutId::FrameBufferBase, kFrameBufferBaseDescriptorBindings.data(),
                       static_cast<uint32_t>(kFrameBufferBaseDescriptorBindings.size()), error))
    return false;
  if (!CreateSetLayout(device, SetLayoutId::FrameBufferTrans, kFrameBufferTransDescriptorBindings.data(),
                       static_cast<uint32_t>(kFrameBufferTransDescriptorBindings.size()), error))
    return false;
  if (!CreateSetLayout(device, SetLayoutId::Tilegen, kTilegenDescriptorBindings.data(),
                       static_cast<uint32_t>(kTilegenDescriptorBindings.size()), error))
    return false;
  if (!CreateSetLayout(device, SetLayoutId::PostProcess, kPostProcessDescriptorBindings.data(),
                       static_cast<uint32_t>(kPostProcessDescriptorBindings.size()), error))
    return false;
  if (!CreateSetLayout(device, SetLayoutId::Crosshair, kCrosshairDescriptorBindings.data(),
                       static_cast<uint32_t>(kCrosshairDescriptorBindings.size()), error))
    return false;
  return true;
}

VkDescriptorSetLayout PipelineCache::SetLayout(SetLayoutId id) const
{
  const size_t index = static_cast<size_t>(id);
  return index < m_setLayouts.size() ? m_setLayouts[index] : VK_NULL_HANDLE;
}

