bool PipelineCache::ValidateKey(const PipelineKey &key, std::string *error) const
{
  if (key.program >= static_cast<uint16_t>(Program::Count))
    return SetError(error, "PipelineKey names a program that does not exist");

  const Program program = static_cast<Program>(key.program);

  if (key.renderPass == 0)
    return SetError(error, std::string("PipelineKey for the ") + ProgramName(program) +
                               " pipeline carries no render pass");

  if (key.colourAttachmentCount == 0 || key.colourAttachmentCount > 4)
    return SetError(error, std::string("PipelineKey for the ") + ProgramName(program) +
                               " pipeline has an unsupported colour attachment count");

  if (program == Program::R3DQuad && !m_geometryShader)
    return SetError(error, "The R3D quad pipeline needs VkPhysicalDeviceFeatures::geometryShader, "
                           "which this device does not expose");

  if (!m_independentBlend && key.colourAttachmentCount > 1)
  {
    // Without independentBlend every attachment blend state, colour write mask included, must
    // be identical, which makes the New3D per-layer masking inexpressible.
    for (uint32_t i = 1; i < key.colourAttachmentCount; ++i)
    {
      if (key.colourWriteMask[i] != key.colourWriteMask[0])
      {
        return SetError(error, "The New3D render passes need per-attachment colour write masks, so "
                               "VkPhysicalDeviceFeatures::independentBlend is required and this "
                               "device does not expose it");
      }
    }
  }

  return true;
}

bool PipelineCache::CreatePipeline(const DeviceContext &device, const PipelineKey &key,
                                   VkPipeline *out, std::string *error)
{
  if (!ValidateKey(key, error))
    return false;

  const Program program = static_cast<Program>(key.program);
  const ProgramInfo &info = InfoFor(program);

  const VkPipelineLayout layout = PipelineLayout(info.layout);
  if (layout == VK_NULL_HANDLE)
    return SetError(error, std::string("The ") + ProgramName(program) +
                               " pipeline layout has not been created");

  std::array<VkPipelineShaderStageCreateInfo, 3> stages{};
  uint32_t stageCount = 0;

  VkShaderModule vertexModule = VK_NULL_HANDLE;
  if (!ShaderModuleHandle(device, info.vertex, &vertexModule, error))
    return false;
  stages[stageCount].sType = VK_STRUCTURE_TYPE_PIPELINE_SHADER_STAGE_CREATE_INFO;
  stages[stageCount].stage = VK_SHADER_STAGE_VERTEX_BIT;
  stages[stageCount].module = vertexModule;
  stages[stageCount].pName = "main";
  ++stageCount;

  if (info.geometry != ShaderModuleId::Count)
  {
    VkShaderModule geometryModule = VK_NULL_HANDLE;
    if (!ShaderModuleHandle(device, info.geometry, &geometryModule, error))
      return false;
    stages[stageCount].sType = VK_STRUCTURE_TYPE_PIPELINE_SHADER_STAGE_CREATE_INFO;
    stages[stageCount].stage = VK_SHADER_STAGE_GEOMETRY_BIT;
    stages[stageCount].module = geometryModule;
    stages[stageCount].pName = "main";
    ++stageCount;
  }

  VkShaderModule fragmentModule = VK_NULL_HANDLE;
  if (!ShaderModuleHandle(device, info.fragment, &fragmentModule, error))
    return false;
  stages[stageCount].sType = VK_STRUCTURE_TYPE_PIPELINE_SHADER_STAGE_CREATE_INFO;
  stages[stageCount].stage = VK_SHADER_STAGE_FRAGMENT_BIT;
  stages[stageCount].module = fragmentModule;
  stages[stageCount].pName = "main";
  ++stageCount;

  // Vertex input. Only the R3D and crosshair programs read a vertex buffer; the
  // rest generate their vertices from gl_VertexIndex, as their GL originals did.
  VkPipelineVertexInputStateCreateInfo vertexInput{};
  vertexInput.sType = VK_STRUCTURE_TYPE_PIPELINE_VERTEX_INPUT_STATE_CREATE_INFO;
  if (info.r3dVertexInput)
  {
    vertexInput.vertexBindingDescriptionCount = 1;
    vertexInput.pVertexBindingDescriptions = &kR3DVertexBindingDescription;
    vertexInput.vertexAttributeDescriptionCount = static_cast<uint32_t>(kR3DVertexAttributes.size());
    vertexInput.pVertexAttributeDescriptions = kR3DVertexAttributes.data();
  }
  else if (info.crosshairVertexInput)
  {
    vertexInput.vertexBindingDescriptionCount = static_cast<uint32_t>(kCrosshairVertexBindings.size());
    vertexInput.pVertexBindingDescriptions = kCrosshairVertexBindings.data();
    vertexInput.vertexAttributeDescriptionCount =
        static_cast<uint32_t>(kCrosshairVertexAttributes.size());
    vertexInput.pVertexAttributeDescriptions = kCrosshairVertexAttributes.data();
  }

  VkPipelineInputAssemblyStateCreateInfo inputAssembly{};
  inputAssembly.sType = VK_STRUCTURE_TYPE_PIPELINE_INPUT_ASSEMBLY_STATE_CREATE_INFO;
  inputAssembly.topology = static_cast<VkPrimitiveTopology>(key.topology);
  inputAssembly.primitiveRestartEnable = VK_FALSE;

  // Dynamic viewport and scissor: no pipeline bakes the render extent.
  VkPipelineViewportStateCreateInfo viewportState{};
  viewportState.sType = VK_STRUCTURE_TYPE_PIPELINE_VIEWPORT_STATE_CREATE_INFO;
  viewportState.viewportCount = 1;
  viewportState.pViewports = nullptr;
  viewportState.scissorCount = 1;
  viewportState.pScissors = nullptr;

  const std::array<VkDynamicState, 2> dynamicStates = {
    VK_DYNAMIC_STATE_VIEWPORT,
    VK_DYNAMIC_STATE_SCISSOR,
  };
  VkPipelineDynamicStateCreateInfo dynamicState{};
  dynamicState.sType = VK_STRUCTURE_TYPE_PIPELINE_DYNAMIC_STATE_CREATE_INFO;
  dynamicState.dynamicStateCount = static_cast<uint32_t>(dynamicStates.size());
  dynamicState.pDynamicStates = dynamicStates.data();

  VkPipelineRasterizationStateCreateInfo rasterization{};
  rasterization.sType = VK_STRUCTURE_TYPE_PIPELINE_RASTERIZATION_STATE_CREATE_INFO;
  rasterization.depthClampEnable = VK_FALSE;
  rasterization.rasterizerDiscardEnable = VK_FALSE;
  rasterization.polygonMode = VK_POLYGON_MODE_FILL;
  rasterization.cullMode = static_cast<VkCullModeFlags>(key.cullMode);
  rasterization.frontFace = static_cast<VkFrontFace>(key.frontFace);
  rasterization.depthBiasEnable = VK_FALSE;
  rasterization.lineWidth = 1.0f;

  VkPipelineMultisampleStateCreateInfo multisample{};
  multisample.sType = VK_STRUCTURE_TYPE_PIPELINE_MULTISAMPLE_STATE_CREATE_INFO;
  multisample.rasterizationSamples = VK_SAMPLE_COUNT_1_BIT;
  multisample.sampleShadingEnable = VK_FALSE;

  // glStencilFunc/glStencilOp affected both faces, so both get the same state.
  VkStencilOpState stencil{};
  stencil.failOp = static_cast<VkStencilOp>(key.stencilFailOp);
  stencil.passOp = static_cast<VkStencilOp>(key.stencilPassOp);
  stencil.depthFailOp = static_cast<VkStencilOp>(key.stencilDepthFailOp);
  stencil.compareOp = static_cast<VkCompareOp>(key.stencilCompareOp);
  stencil.compareMask = key.stencilCompareMask;
  stencil.writeMask = key.stencilWriteMask;
  stencil.reference = key.stencilReference;

  VkPipelineDepthStencilStateCreateInfo depthStencil{};
  depthStencil.sType = VK_STRUCTURE_TYPE_PIPELINE_DEPTH_STENCIL_STATE_CREATE_INFO;
  depthStencil.depthTestEnable = key.depthTestEnable != 0 ? VK_TRUE : VK_FALSE;
  depthStencil.depthWriteEnable = key.depthWriteEnable != 0 ? VK_TRUE : VK_FALSE;
  depthStencil.depthCompareOp = static_cast<VkCompareOp>(key.depthCompareOp);
  depthStencil.depthBoundsTestEnable = VK_FALSE;
  depthStencil.stencilTestEnable = key.stencilTestEnable != 0 ? VK_TRUE : VK_FALSE;
  depthStencil.front = stencil;
  depthStencil.back = stencil;

  std::array<VkPipelineColorBlendAttachmentState, 4> blendAttachments{};
  for (uint32_t i = 0; i < key.colourAttachmentCount; ++i)
  {
    blendAttachments[i].blendEnable = key.blendEnable != 0 ? VK_TRUE : VK_FALSE;
    blendAttachments[i].srcColorBlendFactor = static_cast<VkBlendFactor>(key.srcColorBlendFactor);
    blendAttachments[i].dstColorBlendFactor = static_cast<VkBlendFactor>(key.dstColorBlendFactor);
    blendAttachments[i].colorBlendOp = static_cast<VkBlendOp>(key.colorBlendOp);
    blendAttachments[i].srcAlphaBlendFactor = static_cast<VkBlendFactor>(key.srcAlphaBlendFactor);
    blendAttachments[i].dstAlphaBlendFactor = static_cast<VkBlendFactor>(key.dstAlphaBlendFactor);
    blendAttachments[i].alphaBlendOp = static_cast<VkBlendOp>(key.alphaBlendOp);
    blendAttachments[i].colorWriteMask = static_cast<VkColorComponentFlags>(key.colourWriteMask[i]);
  }

  VkPipelineColorBlendStateCreateInfo colorBlend{};
  colorBlend.sType = VK_STRUCTURE_TYPE_PIPELINE_COLOR_BLEND_STATE_CREATE_INFO;
  colorBlend.logicOpEnable = VK_FALSE;
  colorBlend.logicOp = VK_LOGIC_OP_COPY;
  colorBlend.attachmentCount = key.colourAttachmentCount;
  colorBlend.pAttachments = blendAttachments.data();

  VkGraphicsPipelineCreateInfo createInfo{};
  createInfo.sType = VK_STRUCTURE_TYPE_GRAPHICS_PIPELINE_CREATE_INFO;
  createInfo.stageCount = stageCount;
  createInfo.pStages = stages.data();
  createInfo.pVertexInputState = &vertexInput;
  createInfo.pInputAssemblyState = &inputAssembly;
  createInfo.pViewportState = &viewportState;
  createInfo.pRasterizationState = &rasterization;
  createInfo.pMultisampleState = &multisample;
  createInfo.pDepthStencilState = &depthStencil;
  createInfo.pColorBlendState = &colorBlend;
  createInfo.pDynamicState = &dynamicState;
  createInfo.layout = layout;
  createInfo.renderPass = U64ToRenderPass(key.renderPass);
  createInfo.subpass = key.subpass;
  createInfo.basePipelineHandle = VK_NULL_HANDLE;
  createInfo.basePipelineIndex = -1;

  VkPipeline handle = VK_NULL_HANDLE;
  const VkResult result =
      vkCreateGraphicsPipelines(device.device, m_pipelineCache, 1, &createInfo, nullptr, &handle);
  if (result != VK_SUCCESS)
  {
    std::ostringstream operation;
    operation << "vkCreateGraphicsPipelines for the " << ProgramName(program) << " pipeline";
    return SetError(error, VkError(operation.str().c_str(), result));
  }

  *out = handle;
  return true;
}

VkPipeline PipelineCache::Get(const DeviceContext &device, const PipelineKey &key, std::string *error)
{
  // Cache-hit path: one lookup, no allocation.
  const auto found = m_pipelines.find(key);
  if (found != m_pipelines.end())
    return found->second;

  if (!m_created)
  {
    SetError(error, "PipelineCache::Get called before Create() succeeded");
    return VK_NULL_HANDLE;
  }

  VkPipeline pipeline = VK_NULL_HANDLE;
  if (!CreatePipeline(device, key, &pipeline, error))
    return VK_NULL_HANDLE;

  // If insertion throws, the pipeline would leak, so destroy it and report.
  try
  {
    m_pipelines.emplace(key, pipeline);
  }
  catch (...)
  {
    vkDestroyPipeline(device.device, pipeline, nullptr);
    SetError(error, "PipelineCache ran out of memory inserting a pipeline");
    return VK_NULL_HANDLE;
  }

  return pipeline;
}

bool PipelineCache::Warm(const DeviceContext &device, const PipelineKey *keys, size_t count,
                         std::string *error)
{
  if (keys == nullptr && count != 0)
    return SetError(error, "PipelineCache::Warm received a null key array");

  for (size_t i = 0; i < count; ++i)
  {
    if (Get(device, keys[i], error) == VK_NULL_HANDLE)
      return false;
  }
  return true;
}

bool PipelineCache::Prebuild(const DeviceContext &device, const TargetInfo &targets,
                             std::string *error)
{
  if (targets.scenePass == VK_NULL_HANDLE || targets.sceneColourPass == VK_NULL_HANDLE ||
      targets.outputPass == VK_NULL_HANDLE)
    return SetError(error, "PipelineCache::Prebuild needs all three render passes");
  // Without these MakeR3DKey would silently fall back to the base scene pass and
  // build translucency pipelines that are not compatible with the pass they run in.
  if (targets.scenePassTransFirst == VK_NULL_HANDLE ||
      targets.scenePassTransSecond == VK_NULL_HANDLE || targets.scenePassNoLos == VK_NULL_HANDLE)
    return SetError(error, "PipelineCache::Prebuild needs both translucency render passes and the "
                           "no-LOS base pass");
  if (targets.colourFormat == VK_FORMAT_UNDEFINED || targets.depthStencilFormat == VK_FORMAT_UNDEFINED)
    return SetError(error, "PipelineCache::Prebuild needs the colour and depth/stencil formats");

  std::vector<PipelineKey> keys;
  keys.reserve(40);

  // Both R3D programs, all three layers, both stencil configurations. A layered mesh's
  // stencil state does not depend on noLosReturn, so three combinations per layer, not four.
  const std::array<New3D::Layer, 3> layers = {
    New3D::Layer::colour, New3D::Layer::trans1, New3D::Layer::trans2,
  };
  const std::array<Program, 2> r3dPrograms = { Program::R3DTriangle, Program::R3DQuad };

  for (Program program : r3dPrograms)
  {
    if (program == Program::R3DQuad && (!targets.geometryShader || !m_geometryShader))
      continue;

    for (New3D::Layer layer : layers)
    {
      for (bool losActive : { true, false })
      {
        keys.push_back(MakeR3DKey(targets, program, layer, false, false, losActive));
        keys.push_back(MakeR3DKey(targets, program, layer, false, true, losActive));
        keys.push_back(MakeR3DKey(targets, program, layer, true, false, losActive));
      }
    }
  }

  keys.push_back(MakeScrollFogKey(targets, true));
  keys.push_back(MakeScrollFogKey(targets, false));

  keys.push_back(MakeFrameBufferKey(targets, Program::FrameBufferBase));
  keys.push_back(MakeFrameBufferKey(targets, Program::FrameBufferTrans));
  keys.push_back(MakeFrameBufferKey(targets, Program::FrameBufferBaseScaled));
  keys.push_back(MakeFrameBufferKey(targets, Program::FrameBufferTransScaled));

  // The bottom 2D layer is drawn opaque, the top one blended.
  for (int mode = 0; mode < kTilegenUpscaleModeCount; ++mode)
  {
    keys.push_back(MakeTilegenKey(targets, mode, false));
    keys.push_back(MakeTilegenKey(targets, mode, true));
  }

  keys.push_back(MakePostProcessKey(targets));

  keys.push_back(MakeCrosshairKey(targets, false));
  keys.push_back(MakeCrosshairKey(targets, true));

  return Warm(device, keys.data(), keys.size(), error);
}

