PipelineCache::~PipelineCache()
{
  if (m_created)
    Destroy(m_deviceContext);
}

bool PipelineCache::SetError(std::string *error, const std::string &message)
{
  if (error != nullptr)
    *error = message;
  return false;
}

bool PipelineCache::Create(const DeviceContext &device, std::string *error)
{
  if (m_created)
    Destroy(device);

  if (device.device == VK_NULL_HANDLE || device.physicalDevice == VK_NULL_HANDLE)
    return SetError(error, "PipelineCache::Create received an incomplete DeviceContext");

  m_deviceContext = device;

  VkPhysicalDeviceFeatures features{};
  vkGetPhysicalDeviceFeatures(device.physicalDevice, &features);
  m_independentBlend = features.independentBlend == VK_TRUE;
  m_geometryShader = features.geometryShader == VK_TRUE;

  if (!CreateSetLayouts(device, error) || !CreatePipelineLayouts(device, error) ||
      !CreatePipelineCacheObject(device, error))
  {
    Destroy(device);
    return false;
  }

  m_created = true;
  return true;
}

void PipelineCache::Destroy(const DeviceContext &device)
{
  if (device.device != VK_NULL_HANDLE)
  {
    for (const auto &entry : m_pipelines)
    {
      if (entry.second != VK_NULL_HANDLE)
        vkDestroyPipeline(device.device, entry.second, nullptr);
    }

    ReleaseShaderModules(device);

    if (m_pipelineCache != VK_NULL_HANDLE)
      vkDestroyPipelineCache(device.device, m_pipelineCache, nullptr);

    for (VkPipelineLayout &layout : m_pipelineLayouts)
    {
      if (layout != VK_NULL_HANDLE)
        vkDestroyPipelineLayout(device.device, layout, nullptr);
      layout = VK_NULL_HANDLE;
    }

    for (VkDescriptorSetLayout &layout : m_setLayouts)
    {
      if (layout != VK_NULL_HANDLE)
        vkDestroyDescriptorSetLayout(device.device, layout, nullptr);
      layout = VK_NULL_HANDLE;
    }
  }

  m_pipelines.clear();
  m_pipelineCache = VK_NULL_HANDLE;
  m_pipelineLayouts.fill(VK_NULL_HANDLE);
  m_setLayouts.fill(VK_NULL_HANDLE);
  m_shaderModules.fill(VK_NULL_HANDLE);
  m_created = false;
  m_independentBlend = false;
  m_geometryShader = false;
  m_deviceContext = DeviceContext{};
}

void PipelineCache::ReleaseShaderModules(const DeviceContext &device)
{
  if (device.device == VK_NULL_HANDLE)
    return;

  for (VkShaderModule &module : m_shaderModules)
  {
    if (module != VK_NULL_HANDLE)
      vkDestroyShaderModule(device.device, module, nullptr);
    module = VK_NULL_HANDLE;
  }
}

