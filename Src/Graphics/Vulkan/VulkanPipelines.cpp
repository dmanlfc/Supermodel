bool PipelineKey::operator==(const PipelineKey &other) const
{
  // Legal because the struct is standard layout with explicit padding, and
  // every field is set through the factories or zero-initialized.
  return std::memcmp(this, &other, sizeof(PipelineKey)) == 0;
}

size_t PipelineKeyHash::operator()(const PipelineKey &key) const
{
  // FNV-1a over the packed bytes. No allocation, because Get() runs per mesh.
  const unsigned char *bytes = reinterpret_cast<const unsigned char *>(&key);
  uint64_t hash = 1469598103934665603ull;
  for (size_t i = 0; i < sizeof(PipelineKey); ++i)
  {
    hash ^= static_cast<uint64_t>(bytes[i]);
    hash *= 1099511628211ull;
  }
  return static_cast<size_t>(hash);
}

