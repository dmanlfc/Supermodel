// VkRenderPass is a pointer on 64-bit builds and a uint64_t elsewhere, so it is
// copied bit for bit rather than cast.
static_assert(sizeof(VkRenderPass) == sizeof(uint64_t), "VkRenderPass is not 64 bits wide");

uint64_t HandleToU64(VkRenderPass handle)
{
  uint64_t value = 0;
  std::memcpy(&value, &handle, sizeof(handle));
  return value;
}

VkRenderPass U64ToRenderPass(uint64_t value)
{
  VkRenderPass handle = VK_NULL_HANDLE;
  std::memcpy(&handle, &value, sizeof(handle));
  return handle;
}

// Fills in the target-related fields shared by every key factory.
void SetTarget(PipelineKey &key, VkRenderPass renderPass, VkFormat colourFormat,
               VkFormat depthStencilFormat, uint8_t colourAttachmentCount)
{
  key.renderPass = HandleToU64(renderPass);
  key.colourFormat = static_cast<uint32_t>(colourFormat);
  key.depthStencilFormat = static_cast<uint32_t>(depthStencilFormat);
  key.colourAttachmentCount = colourAttachmentCount;
  key.subpass = 0;
}

// GL_SRC_ALPHA / GL_ONE_MINUS_SRC_ALPHA, which every GL call site used. The factors are
// recorded even when blending is off, as GL set glBlendFunc once and then disabled blending.
void SetSrcAlphaBlend(PipelineKey &key, bool enable)
{
  key.blendEnable = enable ? 1u : 0u;
  key.srcColorBlendFactor = static_cast<uint8_t>(VK_BLEND_FACTOR_SRC_ALPHA);
  key.dstColorBlendFactor = static_cast<uint8_t>(VK_BLEND_FACTOR_ONE_MINUS_SRC_ALPHA);
  key.colorBlendOp = static_cast<uint8_t>(VK_BLEND_OP_ADD);
  key.srcAlphaBlendFactor = static_cast<uint8_t>(VK_BLEND_FACTOR_SRC_ALPHA);
  key.dstAlphaBlendFactor = static_cast<uint8_t>(VK_BLEND_FACTOR_ONE_MINUS_SRC_ALPHA);
  key.alphaBlendOp = static_cast<uint8_t>(VK_BLEND_OP_ADD);
}

void SetNoDepthNoStencil(PipelineKey &key)
{
  key.depthTestEnable = 0;
  key.depthWriteEnable = 0;
  key.depthCompareOp = static_cast<uint8_t>(VK_COMPARE_OP_ALWAYS);
  key.stencilTestEnable = 0;
  key.stencilCompareOp = static_cast<uint8_t>(VK_COMPARE_OP_ALWAYS);
  key.stencilFailOp = static_cast<uint8_t>(VK_STENCIL_OP_KEEP);
  key.stencilPassOp = static_cast<uint8_t>(VK_STENCIL_OP_KEEP);
  key.stencilDepthFailOp = static_cast<uint8_t>(VK_STENCIL_OP_KEEP);
  key.stencilCompareMask = 0;
  key.stencilWriteMask = 0;
  key.stencilReference = 0;
}

// A full-screen pass: no vertex buffer, GL_TRIANGLE_STRIP with four generated
// vertices, no culling.
void SetFullScreenRaster(PipelineKey &key)
{
  key.topology = static_cast<uint8_t>(VK_PRIMITIVE_TOPOLOGY_TRIANGLE_STRIP);
  key.cullMode = static_cast<uint8_t>(VK_CULL_MODE_NONE);
  key.frontFace = static_cast<uint8_t>(VK_FRONT_FACE_COUNTER_CLOCKWISE);
}

const char *ProgramName(Program program)
{
  switch (program)
  {
  case Program::R3DTriangle: return "R3D triangle";
  case Program::R3DQuad: return "R3D quad";
  case Program::ScrollFog: return "scroll fog";
  case Program::FrameBufferBase: return "framebuffer composite base";
  case Program::FrameBufferBaseScaled: return "framebuffer composite base (scaled)";
  case Program::FrameBufferTrans: return "framebuffer composite trans";
  case Program::FrameBufferTransScaled: return "framebuffer composite trans (scaled)";
  case Program::TilegenUpscale0: return "tilegen (nearest)";
  case Program::TilegenUpscale1: return "tilegen (biquintic)";
  case Program::TilegenUpscale2: return "tilegen (bilinear)";
  case Program::TilegenUpscale3: return "tilegen (bicubic)";
  case Program::PostProcess: return "post process";
  case Program::Crosshair: return "crosshair";
  case Program::Count:
  default: return "an unknown program";
  }
}

