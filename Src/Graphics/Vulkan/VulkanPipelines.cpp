bool PipelineCache::CreatePipelineLayout(const DeviceContext &device, PipelineLayoutId id,
                                         SetLayoutId setLayout,
                                         const VkPushConstantRange *pushConstants,
                                         std::string *error)
{
  const VkDescriptorSetLayout descriptorSetLayout = SetLayout(setLayout);
  if (descriptorSetLayout == VK_NULL_HANDLE)
    return SetError(error, "PipelineCache tried to build a pipeline layout before its descriptor set layout");

  VkPipelineLayoutCreateInfo createInfo{};
  createInfo.sType = VK_STRUCTURE_TYPE_PIPELINE_LAYOUT_CREATE_INFO;
  createInfo.setLayoutCount = 1;
  createInfo.pSetLayouts = &descriptorSetLayout;
  createInfo.pushConstantRangeCount = pushConstants != nullptr ? 1u : 0u;
  createInfo.pPushConstantRanges = pushConstants;

  VkPipelineLayout handle = VK_NULL_HANDLE;
  const VkResult result = vkCreatePipelineLayout(device.device, &createInfo, nullptr, &handle);
  if (result != VK_SUCCESS)
    return SetError(error, VkError("vkCreatePipelineLayout", result));

  m_pipelineLayouts[static_cast<size_t>(id)] = handle;
  return true;
}

bool PipelineCache::CreatePipelineLayouts(const DeviceContext &device, std::string *error)
{
  // R3D triangle and quad share this one, push constants included.
  if (!CreatePipelineLayout(device, PipelineLayoutId::R3D, SetLayoutId::R3D,
                            &kR3DPushConstantRange, error))
    return false;

  if (!CreatePipelineLayout(device, PipelineLayoutId::ScrollFog, SetLayoutId::ScrollFog, nullptr, error))
    return false;

  if (!CreatePipelineLayout(device, PipelineLayoutId::FrameBufferBase, SetLayoutId::FrameBufferBase,
                            nullptr, error))
    return false;
  if (!CreatePipelineLayout(device, PipelineLayoutId::FrameBufferBaseScaled,
                            SetLayoutId::FrameBufferBase, &kR3DFrameBufferScaledPushConstantRange,
                            error))
    return false;
  if (!CreatePipelineLayout(device, PipelineLayoutId::FrameBufferTrans, SetLayoutId::FrameBufferTrans,
                            nullptr, error))
    return false;
  if (!CreatePipelineLayout(device, PipelineLayoutId::FrameBufferTransScaled,
                            SetLayoutId::FrameBufferTrans, &kR3DFrameBufferScaledPushConstantRange,
                            error))
    return false;

  // All four upscale variants share one layout, as they share one binding set.
  if (!CreatePipelineLayout(device, PipelineLayoutId::Tilegen, SetLayoutId::Tilegen, nullptr, error))
    return false;

  if (!CreatePipelineLayout(device, PipelineLayoutId::PostProcess, SetLayoutId::PostProcess, nullptr,
                            error))
    return false;

  if (!CreatePipelineLayout(device, PipelineLayoutId::Crosshair, SetLayoutId::Crosshair,
                            &kCrosshairPushConstantRange, error))
    return false;

  return true;
}

VkPipelineLayout PipelineCache::PipelineLayout(PipelineLayoutId id) const
{
  const size_t index = static_cast<size_t>(id);
  return index < m_pipelineLayouts.size() ? m_pipelineLayouts[index] : VK_NULL_HANDLE;
}

VkPipelineLayout PipelineCache::LayoutFor(Program program) const
{
  return PipelineLayout(LayoutIdFor(program));
}

