bool PipelineCache::CreatePipelineCacheObject(const DeviceContext &device, std::string *error)
{
  VkPipelineCacheCreateInfo createInfo{};
  createInfo.sType = VK_STRUCTURE_TYPE_PIPELINE_CACHE_CREATE_INFO;

  const VkResult result = vkCreatePipelineCache(device.device, &createInfo, nullptr, &m_pipelineCache);
  if (result != VK_SUCCESS)
    return SetError(error, VkError("vkCreatePipelineCache", result));
  return true;
}

bool PipelineCache::ShaderModuleHandle(const DeviceContext &device, ShaderModuleId id,
                                       VkShaderModule *out, std::string *error)
{
  const size_t index = static_cast<size_t>(id);
  if (index >= m_shaderModules.size())
    return SetError(error, "PipelineCache asked for an out-of-range shader module");

  if (m_shaderModules[index] != VK_NULL_HANDLE)
  {
    *out = m_shaderModules[index];
    return true;
  }

  const SpirvModule &spirv = kSpirvModules[index];

  VkShaderModuleCreateInfo createInfo{};
  createInfo.sType = VK_STRUCTURE_TYPE_SHADER_MODULE_CREATE_INFO;
  createInfo.codeSize = spirv.bytes;
  createInfo.pCode = spirv.words;

  VkShaderModule handle = VK_NULL_HANDLE;
  const VkResult result = vkCreateShaderModule(device.device, &createInfo, nullptr, &handle);
  if (result != VK_SUCCESS)
  {
    std::ostringstream operation;
    operation << "vkCreateShaderModule for " << spirv.name;
    return SetError(error, VkError(operation.str().c_str(), result));
  }

  m_shaderModules[index] = handle;
  *out = handle;
  return true;
}

