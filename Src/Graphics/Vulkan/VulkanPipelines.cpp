PipelineKey PipelineCache::MakeR3DKey(const TargetInfo &targets, Program program, New3D::Layer layer,
                                      bool layeredMesh, bool noLosReturn, bool losActive)
{
  PipelineKey key{};
  key.program = static_cast<uint16_t>(program == Program::R3DQuad ? Program::R3DQuad
                                                                  : Program::R3DTriangle);
  // Each variant marks a different set of attachments unused, making the variants mutually
  // incompatible, so a pipeline must be built against the exact pass it will run in.
  VkRenderPass scenePass =
      (!losActive && targets.scenePassNoLos != VK_NULL_HANDLE) ? targets.scenePassNoLos
                                                               : targets.scenePass;
  if (layer == New3D::Layer::trans1 && targets.scenePassTransFirst != VK_NULL_HANDLE)
    scenePass = targets.scenePassTransFirst;
  else if (layer == New3D::Layer::trans2 && targets.scenePassTransSecond != VK_NULL_HANDLE)
    scenePass = targets.scenePassTransSecond;

  SetTarget(key, scenePass, targets.colourFormat, targets.depthStencilFormat,
            static_cast<uint8_t>(kScenePassColourAttachmentCount));

  // GL_TRIANGLES for step 1.0, GL_LINES_ADJACENCY for the quad path.
  key.topology = static_cast<uint8_t>(program == Program::R3DQuad
                                          ? VK_PRIMITIVE_TOPOLOGY_LINE_LIST_WITH_ADJACENCY
                                          : VK_PRIMITIVE_TOPOLOGY_TRIANGLE_LIST);

  // glDisable(GL_CULL_FACE): the Real3D backface rule lives in the shader.
  key.cullMode = static_cast<uint8_t>(VK_CULL_MODE_NONE);
  key.frontFace = static_cast<uint8_t>(VK_FRONT_FACE_COUNTER_CLOCKWISE);

  // glBlendFunc set, GL_BLEND disabled.
  SetSrcAlphaBlend(key, false);

  // Reversed-Z. GEQUAL for the base layer, GREATER once the two transparency
  // layers start, matching the glDepthFunc(GL_GREATER) in RenderFrame.
  key.depthTestEnable = 1;
  key.depthWriteEnable = 1;
  key.depthCompareOp = static_cast<uint8_t>(layer == New3D::Layer::colour ? kReversedZCompareOp
                                                                         : VK_COMPARE_OP_GREATER);

  key.stencilTestEnable = 1;
  if (layeredMesh)
  {
    // glStencilFunc(GL_EQUAL, 0, 0b01111111); glStencilOp(KEEP, INCR, INCR).
    key.stencilCompareOp = static_cast<uint8_t>(VK_COMPARE_OP_EQUAL);
    key.stencilReference = 0;
    key.stencilCompareMask = 0x7F;
    key.stencilWriteMask = 0x7F;
    key.stencilFailOp = static_cast<uint8_t>(VK_STENCIL_OP_KEEP);
    key.stencilDepthFailOp = static_cast<uint8_t>(VK_STENCIL_OP_INCREMENT_AND_CLAMP);
    key.stencilPassOp = static_cast<uint8_t>(VK_STENCIL_OP_INCREMENT_AND_CLAMP);
  }
  else
  {
    // glStencilFunc(GL_ALWAYS, noLosReturn << 7, 0b10000000);
    // glStencilOp(KEEP, KEEP, REPLACE).
    key.stencilCompareOp = static_cast<uint8_t>(VK_COMPARE_OP_ALWAYS);
    key.stencilReference = noLosReturn ? 0x80 : 0x00;
    key.stencilCompareMask = 0x80;
    key.stencilWriteMask = 0x80;
    key.stencilFailOp = static_cast<uint8_t>(VK_STENCIL_OP_KEEP);
    key.stencilDepthFailOp = static_cast<uint8_t>(VK_STENCIL_OP_KEEP);
    key.stencilPassOp = static_cast<uint8_t>(VK_STENCIL_OP_REPLACE);
  }

  // R3DFrameBuffers::SetFBO's glDrawBuffers, expressed as write masks.
  switch (layer)
  {
  case New3D::Layer::trans1:
    key.colourWriteMask[kR3DAttachmentColour] = 0;
    key.colourWriteMask[kR3DAttachmentTrans0] = static_cast<uint8_t>(kWriteRGBA);
    key.colourWriteMask[kR3DAttachmentTrans1] = 0;
    key.colourWriteMask[kR3DAttachmentLos] = 0;
    break;
  case New3D::Layer::trans2:
    key.colourWriteMask[kR3DAttachmentColour] = 0;
    key.colourWriteMask[kR3DAttachmentTrans0] = 0;
    key.colourWriteMask[kR3DAttachmentTrans1] = static_cast<uint8_t>(kWriteRGBA);
    key.colourWriteMask[kR3DAttachmentLos] = 0;
    break;
  case New3D::Layer::colour:
  default:
    // Layer::colour writes every buffer; the transparency layers are masked by
    // the shader's own discard rules rather than by state, exactly as in GL.
    key.colourWriteMask[kR3DAttachmentColour] = static_cast<uint8_t>(kWriteRGBA);
    key.colourWriteMask[kR3DAttachmentTrans0] = static_cast<uint8_t>(kWriteRGBA);
    key.colourWriteMask[kR3DAttachmentTrans1] = static_cast<uint8_t>(kWriteRGBA);
    // SetLosFlagWrite(!mesh.layered): a layered poly still mirrors its depth
    // into R but must not disturb the no-LOS-return flag in G.
    key.colourWriteMask[kR3DAttachmentLos] =
        static_cast<uint8_t>(layeredMesh ? kWriteLosDepthOnly : kWriteLosDepthAndFlag);
    break;
  }

  return key;
}

PipelineKey PipelineCache::MakeScrollFogKey(const TargetInfo &targets, bool losActive)
{
  PipelineKey key{};
  key.program = static_cast<uint16_t>(Program::ScrollFog);
  // Drawn inside the base pass, so it follows the same LOS variant.
  const VkRenderPass scenePass =
      (!losActive && targets.scenePassNoLos != VK_NULL_HANDLE) ? targets.scenePassNoLos
                                                               : targets.scenePass;
  SetTarget(key, scenePass, targets.colourFormat, targets.depthStencilFormat,
            static_cast<uint8_t>(kScenePassColourAttachmentCount));

  SetFullScreenRaster(key);
  SetSrcAlphaBlend(key, false);

  // glDepthMask(GL_FALSE) and glDisable(GL_DEPTH_TEST); the stencil test was
  // not enabled at this point in the frame either.
  SetNoDepthNoStencil(key);

  key.colourWriteMask[kR3DAttachmentColour] = static_cast<uint8_t>(kWriteRGBA);
  key.colourWriteMask[kR3DAttachmentTrans0] = static_cast<uint8_t>(kWriteRGBA);
  key.colourWriteMask[kR3DAttachmentTrans1] = static_cast<uint8_t>(kWriteRGBA);
  // ScrollFog.frag declares no LOS output, so attachment 3 must be masked off
  // rather than left to receive undefined values.
  key.colourWriteMask[kR3DAttachmentLos] = 0;

  return key;
}

PipelineKey PipelineCache::MakeFrameBufferKey(const TargetInfo &targets, Program program)
{
  PipelineKey key{};
  switch (program)
  {
  case Program::FrameBufferBase:
  case Program::FrameBufferBaseScaled:
  case Program::FrameBufferTrans:
  case Program::FrameBufferTransScaled:
    key.program = static_cast<uint16_t>(program);
    break;
  default:
    key.program = static_cast<uint16_t>(Program::FrameBufferBase);
    break;
  }

  // The composite draws into the intermediate scene colour, which has no depth.
  SetTarget(key, targets.sceneColourPass, targets.colourFormat, VK_FORMAT_UNDEFINED, 1);

  SetFullScreenRaster(key);

  // R3DFrameBuffers::Draw: glEnable(GL_BLEND) with SRC_ALPHA/ONE_MINUS_SRC_ALPHA,
  // depth test and culling both disabled.
  SetSrcAlphaBlend(key, true);
  SetNoDepthNoStencil(key);

  key.colourWriteMask[0] = static_cast<uint8_t>(kWriteRGBA);
  return key;
}

PipelineKey PipelineCache::MakeTilegenKey(const TargetInfo &targets, int upscaleMode, bool blend)
{
  PipelineKey key{};
  key.program = static_cast<uint16_t>(TilegenProgram(upscaleMode));
  SetTarget(key, targets.sceneColourPass, targets.colourFormat, VK_FORMAT_UNDEFINED, 1);

  SetFullScreenRaster(key);
  SetSrcAlphaBlend(key, blend);
  SetNoDepthNoStencil(key);

  key.colourWriteMask[0] = static_cast<uint8_t>(kWriteRGBA);
  return key;
}

PipelineKey PipelineCache::MakePostProcessKey(const TargetInfo &targets)
{
  PipelineKey key{};
  key.program = static_cast<uint16_t>(Program::PostProcess);
  SetTarget(key, targets.outputPass, targets.colourFormat, VK_FORMAT_UNDEFINED, 1);

  SetFullScreenRaster(key);
  // SuperAA::Draw disabled depth, stencil, scissor and blending.
  SetSrcAlphaBlend(key, false);
  SetNoDepthNoStencil(key);

  key.colourWriteMask[0] = static_cast<uint8_t>(kWriteRGBA);
  return key;
}

PipelineKey PipelineCache::MakeCrosshairKey(const TargetInfo &targets, bool bitmap)
{
  PipelineKey key{};
  key.program = static_cast<uint16_t>(Program::Crosshair);
  SetTarget(key, targets.outputPass, targets.colourFormat, VK_FORMAT_UNDEFINED, 1);

  // CCrosshair drew GL_TRIANGLES from its own vertex buffers.
  key.topology = static_cast<uint8_t>(VK_PRIMITIVE_TOPOLOGY_TRIANGLE_LIST);
  key.cullMode = static_cast<uint8_t>(VK_CULL_MODE_NONE);
  key.frontFace = static_cast<uint8_t>(VK_FRONT_FACE_COUNTER_CLOCKWISE);

  // The bitmap crosshair blends, the vector one does not.
  SetSrcAlphaBlend(key, bitmap);
  SetNoDepthNoStencil(key);

  key.colourWriteMask[0] = static_cast<uint8_t>(kWriteRGBA);
  return key;
}

